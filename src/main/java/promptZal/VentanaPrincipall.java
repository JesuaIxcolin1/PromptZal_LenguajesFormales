    private void btnAbrirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAbrirActionPerformed
        //**************Abrir Archivo***********************
        JFileChooser seleccionarArchivo = new JFileChooser();
        FileNameExtensionFilter filtro = new FileNameExtensionFilter("Archivos PromptZal (*.pz)", "pz");
        
        seleccionarArchivo.setFileFilter(filtro);
        int opcion = seleccionarArchivo.showOpenDialog(this);
        
        if(opcion == JFileChooser.APPROVE_OPTION){
            
            File archivoSeleccionado = seleccionarArchivo.getSelectedFile();
            
            if(!archivoSeleccionado.getName().endsWith(".pz")){
                JOptionPane.showMessageDialog(this, "El archivo debe tener extension .pz", "Archivo no valido", JOptionPane.ERROR_MESSAGE);
                
                return;
        }
            
            rutaActual = archivoSeleccionado.getAbsolutePath();
            Archivo archivo = new Archivo();
            String contenido = archivo.leerArchivo(rutaActual);
            txtEditor.setText(contenido);
            
            JOptionPane.showMessageDialog(this, "Archivo abierto Correctamente");
        }
    }//GEN-LAST:event_btnAbrirActionPerformed

    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        //************Guardar Archivo**********************
        
        //Si todavia no existe un ruta
        if(rutaActual == null){
            JFileChooser seleccionarArchivo = new JFileChooser();
            FileNameExtensionFilter filtro = new FileNameExtensionFilter("Archivos PromptZal (*.pz)","pz");
            seleccionarArchivo.setFileFilter(filtro);
            
            int opcion = seleccionarArchivo.showSaveDialog(this);
            
            if(opcion == JFileChooser.APPROVE_OPTION){
                
                File archivoSeleccionado = seleccionarArchivo.getSelectedFile();
                rutaActual = archivoSeleccionado.getAbsolutePath();
                
                // Agrega la extencion .pz si el usuario no la escribio
                if(!rutaActual.endsWith(".pz")){
                    rutaActual = rutaActual+".pz";
                }
            }else{
                return;
            }
        }
        
        //Guardar el Contenido del Editor
        Archivo archivo = new Archivo();
        archivo.guardarArchivo(rutaActual, txtEditor.getText());
        
        JOptionPane.showMessageDialog(this, "Archivo Guardado Correctamente");
        
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnAnalizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAnalizarActionPerformed
        // **************Analizar Codigo******************
        String texto = txtEditor.getText();
        
        //Verifica que haya contenido
        if(texto.isEmpty()){
            JOptionPane.showMessageDialog(this, "No hay contenido para analizar", "Analizador Lexico",
                    JOptionPane.WARNING_MESSAGE);
            
            return;
        }
        
        //Crea el analizador
        analizadorActual = new analizadorLexico(texto);
        //Realiza el analisis
        analizadorActual.analizador();
        
        mostrarTokens();
        mostrarErrores();
        
        JOptionPane.showMessageDialog(this,"Analisis lexico Terminado\n"+"Tokens Encontrados: "
        +analizadorActual.getlistaTokens().size()+"\nErrores Encontrados: "+ analizadorActual.getlistaErrores().size());
        
    }//GEN-LAST:event_btnAnalizarActionPerformed

